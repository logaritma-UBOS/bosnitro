export default function DesktopSidebar({ businessName, role = "OWNER" }: { businessName?: string, role?: string }) {
  const pathname = usePathname()
  const [tier, setTier] = useState<string>("Starter")

  useEffect(() => {
    fetch("/api/user/status").then(r => r.json()).then(d => {
      setTier(d.tier || "Starter")
    }).catch(() => {})
  }, [])
  
  // Active check: exact for /, startsWith for others
  const isActive = (href: string) => {
    if (href === "/" || href === "/beranda") return pathname === "/" || pathname === "/beranda"
    return pathname === href || pathname.startsWith(href + "/")
  }

  const isLocked = (label: string) => {
    if (tier === "Starter") {
      const lockedFeatures = ["Pelanggan", "Pengeluaran", "Stok & Supplier", "Promo", "Marketing", "Konten"]
      return lockedFeatures.includes(label)
    }
    return false
  }

  return (
    <aside className="hidden lg:flex flex-col w-60 xl:w-64 shrink-0 h-screen sticky top-0 bg-white border-r border-gray-200 shadow-sm overflow-y-auto">
      {/* Logo + Business Name */}
      <div className="px-5 py-5 border-b border-gray-100">
        <Image src="/logo-ubos.png" alt="UBOS" width={90} height={28} className="h-7 w-auto object-contain mb-2" />
        {businessName && (
          <p className="text-xs font-bold text-gray-600 truncate">{businessName}</p>
        )}
      </div>

      {/* Navigation Groups */}
      <nav className="flex-1 px-3 py-4 space-y-5">
        {navGroups.map((group) => (
          <div key={group.label ?? "home"}>
            {group.label && (
              <p className="text-[9px] font-black text-gray-400 uppercase tracking-[0.14em] px-2 mb-1.5">
                {group.label}
              </p>
            )}
            <div className="space-y-0.5">

              {group.items.map((item) => {
                if (role === 'KASIR') {
                  const allowedKasir = ["/kasir"];
                  if (!allowedKasir.includes(item.href)) return null;
                } else if (role === 'MANAGER') {
                  const allowedManager = ["/kasir", "/stok", "/katalog"];
                  if (!allowedManager.includes(item.href)) return null;
                }

                const active = isActive(item.href)
                const locked = isLocked(item.label)

                if (locked) {
                  return (
                    <div
                      key={item.href}
                      className="flex items-center justify-between px-3 py-2.5 rounded-xl text-sm font-semibold text-gray-400 bg-gray-50/50 cursor-not-allowed border border-transparent"
                    >
                      <div className="flex items-center gap-3">
                        <span className="shrink-0 text-gray-300">{item.icon}</span>
                        <span>{item.label}</span>
                      </div>
                      <svg xmlns="http://www.w3.org/2000/svg" fill="none" viewBox="0 0 24 24" strokeWidth={2} stroke="currentColor" className="w-3.5 h-3.5 text-gray-400">
                        <path strokeLinecap="round" strokeLinejoin="round" d="M16.5 10.5V6.75a4.5 4.5 0 10-9 0v3.75m-.75 11.25h10.5a2.25 2.25 0 002.25-2.25v-6.75a2.25 2.25 0 00-2.25-2.25H6.75a2.25 2.25 0 00-2.25 2.25v6.75a2.25 2.25 0 002.25 2.25z" />
                      </svg>
                    </div>
                  )
                }

                return (
                  <Link
                    key={item.href}
                    href={item.href}
                    className={`flex items-center gap-3 px-3 py-2.5 rounded-xl text-sm font-semibold transition-all duration-150
                      ${active
                        ? "bg-emerald-50 text-emerald-700 border border-emerald-100 shadow-sm"
                        : "text-gray-600 hover:bg-gray-100 hover:text-gray-900 border border-transparent"
                      }`}
                  >
                    <span className={`shrink-0 ${active ? "text-emerald-600" : "text-gray-400"}`}>
                      {item.icon}
                    </span>
                    <span className={active ? "font-bold" : ""}>{item.label}</span>
                    {active && (
                      <span className="ml-auto w-1.5 h-1.5 rounded-full bg-emerald-500 shrink-0" />
                    )}
                  </Link>
                )
              })}
            </div>
          </div>
        ))}
      </nav>

      
      {/* LOGOUT */}
      <div className="px-3 mt-auto mb-2">
        <form action={logoutUser}>
          <button type="submit" className="w-full flex items-center gap-3 px-3 py-2.5 rounded-xl text-sm font-semibold text-red-600 hover:bg-red-50 transition-colors">
            <svg xmlns="http://www.w3.org/2000/svg" fill="none" viewBox="0 0 24 24" strokeWidth={2} stroke="currentColor" className="w-5 h-5 shrink-0">
              <path strokeLinecap="round" strokeLinejoin="round" d="M15.75 9V5.25A2.25 2.25 0 0013.5 3h-6a2.25 2.25 0 00-2.25 2.25v13.5A2.25 2.25 0 007.5 21h6a2.25 2.25 0 002.25-2.25V15M12 9l-3 3m0 0l3 3m-3-3h12.75" />
            </svg>
            Keluar
          </button>
        </form>
      </div>
      {/* Footer version */}
      <div className="px-5 py-3 border-t border-gray-100">
        <p className="text-[10px] text-gray-400 font-medium">UBOS Â© 2026</p>
      </div>
    </aside>
  )
}



